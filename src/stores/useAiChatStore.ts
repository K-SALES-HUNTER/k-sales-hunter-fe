const FALLBACK_ANSWER =
  '그 질문은 지금 열려 있는 분석 결과만으로는 답하기 어려워요. 제가 도와드릴 수 있는 건 이런 것들입니다.\n\n• 지금 화면의 분석 결과와 계산 근거 설명\n• 가격·옵션·재고·배송 방식에 대한 판단 근거\n• 보고서 재생성, 다른 국가 추가 분석, 입력 정보 수정 요청\n\n왼쪽 보고서에서 궁금한 항목을 짚어 물어봐 주시면 그 근거부터 설명드릴게요.';

/** [DEMO-ONLY] 답변 길이에 비례한 생성 지연 (0.6~1.6초) — 실제 스트리밍 응답과 비슷한 체감을 준다 */
const replyDelay = (text: string) => Math.min(1600, 600 + text.length * 2.4);

let nextId = 1;

/**
 * AI 패널 대화 스토어 (Figma 335:3411 주석: 페이지가 바뀌어도 대화 내용 유지)
 * 세션 동안 유지 — sessionStorage persist.
 */
export const useAiChatStore = create<AiChatState>()(
  persist(
    (set) => ({
      messages: [],
      replying: false,
      send: (text) => {
        const question = text.trim();
        const answer = ANSWERS[question] ?? FALLBACK_ANSWER;
        set((s) => ({
          messages: [...s.messages, { id: nextId++, role: 'user', text: question }],
          replying: true,
        }));
        setTimeout(() => {
          set((s) => ({
            messages: [...s.messages, { id: nextId++, role: 'ai', text: answer }],
            replying: false,
          }));
        }, replyDelay(answer));
      },
    }),
    {
      name: 'ksh-ai-chat',
      storage: createJSONStorage(() => sessionStorage),
      partialize: (s) => ({ messages: s.messages }),
      onRehydrateStorage: () => (state) => {
        if (state) nextId = Math.max(0, ...state.messages.map((m) => m.id)) + 1;
      },
    },
  ),
);
